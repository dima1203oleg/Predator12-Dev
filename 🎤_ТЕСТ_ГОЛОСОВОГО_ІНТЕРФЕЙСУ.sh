#!/bin/bash

# 🎤 ТЕСТОВИЙ СКРИПТ ГОЛОСОВОГО ІНТЕРФЕЙСУ NEXUS V5.2

echo "🎤 =================================================="
echo "🔊 ТЕСТУВАННЯ ГОЛОСОВОГО ІНТЕРФЕЙСУ NEXUS V5.2"
echo "🎤 =================================================="
echo ""

# Кольоровий вивід
print_status() {
    echo -e "\033[32m✅ $1\033[0m"
}

print_info() {
    echo -e "\033[34mℹ️  $1\033[0m"
}

print_warning() {
    echo -e "\033[33m⚠️  $1\033[0m"
}

# Перевірка браузера та доступу до мікрофону
echo "🔍 ПЕРЕВІРКА ГОТОВНОСТІ СИСТЕМИ:"
echo ""

print_info "1. Переконайтесь, що ваш браузер підтримує Web Speech API"
print_info "2. Дозвольте доступ до мікрофону коли браузер запитає"
print_info "3. Перевірте, що мікрофон підключений та працює"
print_info "4. Переконайтесь, що звук увімкнений"

echo ""
echo "🎯 ТЕСТОВІ КОМАНДИ ДЛЯ ПЕРЕВІРКИ:"
echo ""

echo "📝 ОСНОВНІ КОМАНДИ:"
echo "   • 'привіт' - привітання від AI асистента"
echo "   • 'допомога' - список доступних команд"
echo "   • 'статус системи' - перевірка стану всіх систем"
echo "   • 'тест голосу' - повне тестування TTS та STT"
echo ""

echo "🎤 ТЕСТУВАННЯ МІКРОФОНУ:"
echo "   • 'тестування мікрофону' - перевірка якості запису"
echo "   • 'перевірка звуку' - тест озвучування"
echo "   • 'мікрофон працює' - підтвердження аудіо"
echo ""

echo "🌐 МУЛЬТИМОВНІСТЬ:"
echo "   • 'українська мова' - переключення на українську"
echo "   • 'switch to english' - переключення на англійську"
echo "   • 'hello nexus' - англійське привітання"
echo ""

echo "🚀 НАВІГАЦІЯ ПО МОДУЛЯХ:"
echo "   • 'відкрий дашборд' - головна панель"
echo "   • 'покажи агентів' - модуль AI агентів"
echo "   • 'відкрий аналітику' - статистика та метрики"
echo "   • 'безпека' - центр кібербезпеки"
echo "   • '3d візуалізація' - тривимірний інтерфейс"
echo "   • 'колаборація' - командна робота"
echo ""

echo "⚡ ШВИДКИЙ ТЕСТ:"
echo ""

read -p "🚀 Запустити браузер для тестування? (y/n): " -n 1 -r
echo
if [[ $REPLY =~ ^[Yy]$ ]]; then
    print_status "Запускаю браузер..."

    # Перевірка чи працює сервер
    if curl -s http://localhost:5094 > /dev/null 2>&1; then
        print_status "Сервер доступний на http://localhost:5094"

        # Відкриваємо прямо голосовий інтерфейс
        if command -v open > /dev/null; then
            open "http://localhost:5094#voice-interface"  # macOS
        elif command -v xdg-open > /dev/null; then
            xdg-open "http://localhost:5094#voice-interface"  # Linux
        elif command -v start > /dev/null; then
            start "http://localhost:5094#voice-interface"  # Windows
        else
            echo "🌐 Відкрийте браузер: http://localhost:5094#voice-interface"
        fi

        echo ""
        print_status "Голосовий інтерфейс запущено!"
        echo ""
        print_info "🎤 ПРОБНИЙ АЛГОРИТМ ТЕСТУВАННЯ:"
        echo ""
        echo "1️⃣  Натисніть 'Почати слухати' або 'Тест голосу'"
        echo "2️⃣  Дозвольте доступ до мікрофону"
        echo "3️⃣  Скажіть: 'привіт Нексус'"
        echo "4️⃣  Почекайте відповіді AI асистента"
        echo "5️⃣  Спробуйте команди зі списку вище"
        echo "6️⃣  Перевірте якість озвучування"
        echo ""
        print_warning "Якщо голос не чути, натисніть кнопку 'Тест голосу'"

    else
        print_warning "Сервер не доступний. Запустіть dev server:"
        echo "cd predator12-local/frontend && npm run dev -- --port 5094"
    fi
else
    echo ""
    print_info "Для тестування відкрийте: http://localhost:5094#voice-interface"
fi

echo ""
echo "🔧 НАЛАШТУВАННЯ ГОЛОСУ:"
echo "   • Швидкість: 0.5 - 2.0 (рекомендується 1.0)"
echo "   • Тон: 0.5 - 2.0 (рекомендується 1.0)"
echo "   • Гучність: 0.0 - 1.0 (рекомендується 0.8)"
echo "   • Мова: uk-UA (українська) або en-US (англійська)"
echo ""

echo "🐛 ВИРІШЕННЯ ПРОБЛЕМ:"
echo "   • Немає звуку: Перевірте гучність системи та браузера"
echo "   • Не розпізнає: Говоріть чітко та близько до мікрофону"
echo "   • Помилки: Перезавантажте сторінку та дозвольте доступ"
echo "   • Лаги: Перевірте інтернет з'єднання"
echo ""

print_status "Голосовий інтерфейс Nexus V5.2 готовий до тестування! 🎉"

echo ""
echo "🎤 =================================================="
echo "    Приємного тестування голосового AI! 🚀"
echo "🎤 =================================================="
